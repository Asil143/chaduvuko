        <P>
          Monitor authorization denials and unusual retrieval patterns using minimized metadata. Restrict access to traces,
          set retention based on operational need, and avoid sending unnecessary PII to model providers. A security test should
          prove that a denied document never enters the model request—not merely that the final answer omitted its text.
        </P>
